#!/usr/bin/env node
// Validates every characters/*.json against characters/schema.json and regenerates characters/index.ts.
// Run after adding or editing a character:  npm run check
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "characters");
const schema = JSON.parse(readFileSync(join(dir, "schema.json"), "utf8"));
const HEX = /^#[0-9a-f]{6}$/i;
const ID = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const problems = [];
const files = readdirSync(dir).filter((f) => f.endsWith(".json") && f !== "schema.json").sort();
const ids = [];

for (const f of files) {
  const where = `characters/${f}`;
  let c;
  try { c = JSON.parse(readFileSync(join(dir, f), "utf8")); } catch (e) { problems.push(`${where}: not valid JSON (${e.message})`); continue; }
  const bad = (m) => problems.push(`${where}: ${m}`);
  if (!ID.test(c.id ?? "")) bad(`id must be lowercase-with-dashes, got ${JSON.stringify(c.id)}`);
  if (`${c.id}.json` !== f) bad(`file name must be ${c.id}.json`);
  for (const k of ["name", "short", "tagline", "persona", "voice", "greeting"]) if (typeof c[k] !== "string" || !c[k].trim()) bad(`"${k}" is required`);
  if (typeof c.years !== "string") bad(`"years" must be a string ("" is fine for originals)`);
  if (!schema.kind.includes(c.kind)) bad(`"kind" must be one of ${schema.kind.join(", ")}`);
  if (c.tagline?.length > 80) bad(`"tagline" is over 80 characters`);
  if (c.short?.length > 16) bad(`"short" is over 16 characters`);
  if (!Array.isArray(c.examples) || c.examples.length < 2 || c.examples.some((x) => typeof x !== "string")) bad(`"examples" needs 2 or more lines`);
  const a = c.avatar ?? {};
  for (const k of ["skin", "hairColor", "outfitColor", "bg"]) if (!HEX.test(a[k] ?? "")) bad(`avatar.${k} must be a #rrggbb colour`);
  if (a.facialColor !== undefined && !HEX.test(a.facialColor)) bad(`avatar.facialColor must be a #rrggbb colour`);
  for (const [k, allowed] of Object.entries(schema.avatar)) if (!allowed.includes(a[k])) bad(`avatar.${k} must be one of ${allowed.join(", ")} (got ${JSON.stringify(a[k])})`);
  if (ids.includes(c.id)) bad(`duplicate id ${c.id}`);
  ids.push(c.id);
}

if (problems.length) {
  console.error(problems.map((p) => `✗ ${p}`).join("\n"));
  process.exit(1);
}

const FEATURED = ["einstein", "joe-rogan", "steve-jobs", "cleopatra", "socrates", "frida-kahlo", "nikola-tesla", "gran"].filter((id) => ids.includes(id));
const name = (id) => id.replace(/-([a-z0-9])/g, (_, ch) => ch.toUpperCase()).replace(/^(\d)/, "_$1");
const out = `// Generated by scripts/check-characters.mjs. Do not edit; add a JSON file and run \`npm run check\`.
import type { Character } from "@/lib/types";
${ids.map((id) => `import ${name(id)} from "./${id}.json";`).join("\n")}

/** Featured first; everyone else alphabetical. */
const FEATURED = ${JSON.stringify(FEATURED)};
const all = [${ids.map(name).join(", ")}] as Character[];
export const BUILT_IN = [...FEATURED.map((id) => all.find((c) => c.id === id)!).filter(Boolean), ...all.filter((c) => !FEATURED.includes(c.id))];
`;
writeFileSync(join(dir, "index.ts"), out);
console.log(`✓ ${ids.length} characters ok: ${ids.join(", ")}`);
